"""Documentation consistency tests (stdlib only, no Rust build needed).

The real checks live in ``scripts/check_docs.py`` so CI can run them
with plain ``python``; this test just executes that script end to end.
See docs/FEATURES.md (generated by ``scripts/generate_feature_table.py``)
and the E1 roadmap item (docs/ROADMAP.md).
"""

import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def test_docs_check_passes():
    result = subprocess.run(
        [sys.executable, str(ROOT / "scripts" / "check_docs.py")],
        capture_output=True,
        text=True,
        cwd=ROOT,
    )
    assert result.returncode == 0, (
        "scripts/check_docs.py failed:\n" + result.stdout + result.stderr
    )


def test_generated_feature_table_is_fresh():
    result = subprocess.run(
        [sys.executable, str(ROOT / "scripts" / "generate_feature_table.py"), "--check"],
        capture_output=True,
        text=True,
        cwd=ROOT,
    )
    assert result.returncode == 0, (
        "docs/FEATURES.md is stale:\n" + result.stdout + result.stderr
    )
