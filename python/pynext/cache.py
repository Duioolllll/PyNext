"""ISR coordination over a pluggable page cache backend.

Two layers:

* A process-local L1 (the Rust ``PageCache``) serves fresh hits without
  Python dispatch when no shared backend is configured.
* An optional shared backend (SQLite, spec v0.2 section 10.3) stores
  entries in one file all workers open, so a page generated by one
  worker is served by the others.

The shared backend adds cross-process single-flight: a worker that
regenerates a stale entry first takes a lease on the key (owner token +
expiry). Other workers serve the stale entry while the lease is held.
Every shared write atomically checks both the observed entry version and
the live lease owner. Invalidation removes the lease with the entry, so
an old generation cannot refill the shared cache after invalidation.

Private responses are never stored in the shared cache: a response
with ``Set-Cookie`` or ``Cache-Control: private``/``no-store`` is served
but not written to either layer (spec section 10.2). Requests carrying
a Cookie or Authorization header bypass the cache entirely in
``App.dispatch`` and never reach this module.
"""
import asyncio
import contextvars
import logging
import os
import sqlite3
import threading
import time
import uuid
from collections import OrderedDict

from . import _native
from .failure_policy import FAIL_CLOSED, FAIL_OPEN, normalize_failure_policy

log = logging.getLogger("pynext")
MAX_INFLIGHT = 128
GENERATION_TIMEOUT = 30.0
# A lease outlives one generation attempt so a slow render is not
# immediately duplicated by another worker; fencing still protects the
# write if the lease expires mid-generation.
LEASE_TTL = GENERATION_TIMEOUT + 5.0
LEASE_WAIT_INTERVAL = 0.05
MAX_CACHE_KEY_BYTES = 4096
MAX_CACHE_BODY_BYTES = 2_097_152
MAX_CACHE_SECONDS = 604_800.0
_SHARED_UNAVAILABLE = object()
_VARIANT_GENERATION_TTL = 86400
_MAX_LOCAL_VARIANT_PATHS = 1024


class CacheBusy(Exception):
    pass


class SharedCacheUnavailable(Exception):
    """A shared backend operation failed rather than observing a cache miss."""


class CacheBackend:
    """get/set/delete with TTL.

    ``lookup`` returns ``("fresh" | "stale" | "expired" | "miss", body)``.
    ``insert`` returns False instead of raising when the entry cannot be
    stored (oversized body, invalid durations, backend error); the caller
    keeps serving the freshly rendered body and logs the failure.
    """

    def lookup(self, key):
        raise NotImplementedError

    def insert(self, key, body, fresh_seconds, stale_seconds):
        raise NotImplementedError

    def remove(self, key):
        raise NotImplementedError

    def close(self):
        pass


def _valid_durations(fresh_seconds, stale_seconds):
    try:
        fresh = float(fresh_seconds)
        stale = float(stale_seconds)
    except (TypeError, ValueError):
        return False
    return (0.0 < fresh <= MAX_CACHE_SECONDS and 0.0 <= stale <= MAX_CACHE_SECONDS
            and fresh == fresh and stale == stale)


class MemoryCacheBackend(CacheBackend):
    """The original process-local backend, backed by the Rust PageCache."""

    def __init__(self, store=None):
        self._store = store if store is not None else _native.PageCache()

    @property
    def store(self):
        return self._store

    def lookup(self, key):
        return self._store.lookup(key)

    def insert(self, key, body, fresh_seconds, stale_seconds):
        return self._store.insert(key, body, fresh_seconds, stale_seconds)

    def remove(self, key):
        return self._store.remove(key)


class SharedEntry:
    """One shared-cache row as observed by a lookup."""

    __slots__ = ("status", "body", "version", "fresh_remaining", "stale_remaining")

    def __init__(self, status, body, version, fresh_remaining, stale_remaining):
        self.status = status
        self.body = body
        self.version = version
        self.fresh_remaining = fresh_remaining
        self.stale_remaining = stale_remaining


class SQLiteCacheBackend(CacheBackend):
    """A cross-process cache backend on one SQLite file (WAL mode).

    No external service is needed, so CI and multi-worker deployments
    can share a cache with only the standard library. All statements run
    under one connection guarded by a lock, with ``BEGIN IMMEDIATE`` for
    lease and fenced-write transactions so two processes cannot both win
    the same lease or the same version check. Timestamps use wall-clock
    seconds; a clock jump may age entries early or late, but versions
    still fence every write.
    """

    def __init__(self, path):
        path = os.fspath(path)
        if os.path.isdir(path):
            raise ValueError(f"SQLite cache path is a directory: {path}")
        parent = os.path.dirname(os.path.abspath(path))
        try:
            os.makedirs(parent, exist_ok=True)
        except OSError as exc:
            raise ValueError(f"Cannot create SQLite cache directory {parent}: {exc}") from exc
        self.path = path
        self._lock = threading.RLock()
        try:
            self._conn = sqlite3.connect(path, timeout=10.0, check_same_thread=False)
            self._conn.execute("PRAGMA journal_mode=WAL")
            self._conn.execute("PRAGMA synchronous=NORMAL")
            self._conn.execute("PRAGMA busy_timeout=10000")
            self._conn.executescript(
                "CREATE TABLE IF NOT EXISTS entries ("
                "  key TEXT PRIMARY KEY, body BLOB NOT NULL,"
                "  generated_at REAL NOT NULL, fresh_for REAL NOT NULL,"
                "  stale_for REAL NOT NULL, version INTEGER NOT NULL);"
                "CREATE TABLE IF NOT EXISTS leases ("
                "  key TEXT PRIMARY KEY, owner TEXT NOT NULL,"
                "  expires_at REAL NOT NULL, version INTEGER NOT NULL);"
                "CREATE TABLE IF NOT EXISTS variant_generations ("
                "  key TEXT PRIMARY KEY, token TEXT NOT NULL, expires_at REAL NOT NULL);"
            )
            self._conn.commit()
        except sqlite3.Error as exc:
            raise ValueError(f"Cannot open SQLite cache at {path}: {exc}") from exc

    def _read_entry(self, key, now):
        for _ in range(3):
            row = self._conn.execute(
                "SELECT body, generated_at, fresh_for, stale_for, version"
                " FROM entries WHERE key = ?", (key,)
            ).fetchone()
            if row is None:
                return None
            body, generated_at, fresh_for, stale_for, version = row
            age = now - generated_at
            if age >= fresh_for + stale_for:
                lease = self._conn.execute(
                    "SELECT 1 FROM leases WHERE key = ? AND expires_at > ?", (key, now)
                ).fetchone()
                if lease is not None:
                    return SharedEntry("expired", None, version, 0.0, 0.0)
                # Another connection can replace the row between the read
                # and delete, or take a lease. Delete only the exact expired
                # version seen, and only if no live generation owns it.
                deleted = self._conn.execute(
                    "DELETE FROM entries WHERE key = ? AND version = ? AND generated_at = ?"
                    " AND NOT EXISTS (SELECT 1 FROM leases WHERE key = ? AND expires_at > ?)",
                    (key, version, generated_at, key, now),
                ).rowcount
                self._conn.commit()
                if deleted:
                    return SharedEntry("expired", None, version, 0.0, 0.0)
                now = time.time()
                continue
            if age < fresh_for:
                return SharedEntry("fresh", body, version, fresh_for - age, stale_for)
            return SharedEntry("stale", body, version, 0.0, fresh_for + stale_for - age)
        # A heavily contended key is retried on the next lookup.
        return None

    def lookup(self, key):
        with self._lock:
            try:
                entry = self._read_entry(key, time.time())
            except sqlite3.Error:
                log.warning("Shared cache lookup failed for %s", key, exc_info=True)
                return ("miss", None)
            if entry is None:
                return ("miss", None)
            return (entry.status, entry.body)

    def lookup_entry(self, key):
        """Like ``lookup`` but also returns the entry version and the
        remaining fresh/stale windows, which callers need for fencing and
        for repopulating the process-local cache."""
        with self._lock:
            try:
                return self._read_entry(key, time.time())
            except sqlite3.Error as exc:
                raise SharedCacheUnavailable("Shared cache lookup failed") from exc

    def insert(self, key, body, fresh_seconds, stale_seconds):
        return self.insert_fenced(key, body, fresh_seconds, stale_seconds, None)

    def insert_fenced(self, key, body, fresh_seconds, stale_seconds, expected_version, owner=None):
        """Store ``body`` only if the entry version still equals
        ``expected_version`` (``0`` when no entry existed, ``None`` for an
        unfenced write). When an owner is given, its lease must still be live
        in the same transaction. Returns False when either fence has moved."""
        if len(key.encode("utf-8")) > MAX_CACHE_KEY_BYTES or len(body) > MAX_CACHE_BODY_BYTES:
            return False
        if not _valid_durations(fresh_seconds, stale_seconds):
            return False
        with self._lock:
            try:
                self._conn.execute("BEGIN IMMEDIATE")
                try:
                    now = time.time()
                    if owner is not None:
                        lease = self._conn.execute(
                            "SELECT owner, expires_at FROM leases WHERE key = ?", (key,)
                        ).fetchone()
                        if lease is None or lease[0] != owner or lease[1] <= now:
                            self._conn.execute("ROLLBACK")
                            return False
                    row = self._conn.execute(
                        "SELECT version FROM entries WHERE key = ?", (key,)
                    ).fetchone()
                    if expected_version is None:
                        version = (row[0] + 1) if row else 1
                    elif row is None:
                        if expected_version != 0:
                            self._conn.execute("ROLLBACK")
                            return False
                        version = 1
                    elif row[0] != expected_version:
                        self._conn.execute("ROLLBACK")
                        return False
                    else:
                        version = row[0] + 1
                    self._conn.execute(
                        "INSERT INTO entries (key, body, generated_at, fresh_for, stale_for, version)"
                        " VALUES (?, ?, ?, ?, ?, ?)"
                        " ON CONFLICT(key) DO UPDATE SET body=excluded.body,"
                        " generated_at=excluded.generated_at, fresh_for=excluded.fresh_for,"
                        " stale_for=excluded.stale_for, version=excluded.version",
                        (key, bytes(body), now, float(fresh_seconds), float(stale_seconds), version),
                    )
                    self._conn.execute("COMMIT")
                except BaseException:
                    if self._conn.in_transaction:
                        self._conn.execute("ROLLBACK")
                    raise
                return True
            except sqlite3.Error:
                log.warning("Shared cache insert failed for %s", key, exc_info=True)
                return False

    def remove(self, key):
        with self._lock:
            try:
                self._conn.execute("BEGIN IMMEDIATE")
                try:
                    entry = self._conn.execute("DELETE FROM entries WHERE key = ?", (key,)).rowcount
                    lease = self._conn.execute("DELETE FROM leases WHERE key = ?", (key,)).rowcount
                    self._conn.execute("COMMIT")
                    return entry > 0 or lease > 0
                except BaseException:
                    if self._conn.in_transaction:
                        self._conn.execute("ROLLBACK")
                    raise
            except sqlite3.Error:
                log.warning("Shared cache remove failed for %s", key, exc_info=True)
                return False

    def variant_generation(self, key, *, invalidate=False):
        """Get or replace a path generation atomically across workers."""
        with self._lock:
            try:
                now = time.time()
                if not invalidate:
                    row = self._conn.execute(
                        "SELECT token FROM variant_generations WHERE key=? AND expires_at>?",
                        (key, now)).fetchone()
                    if row:
                        return row[0], True
                self._conn.execute("BEGIN IMMEDIATE")
                try:
                    row = self._conn.execute(
                        "SELECT token FROM variant_generations WHERE key=? AND expires_at>?",
                        (key, now)).fetchone()
                    if row and not invalidate:
                        token = row[0]
                    else:
                        token = uuid.uuid4().hex
                        self._conn.execute(
                            "INSERT INTO variant_generations(key, token, expires_at) VALUES(?,?,?) "
                            "ON CONFLICT(key) DO UPDATE SET token=excluded.token, expires_at=excluded.expires_at",
                            (key, token, now + _VARIANT_GENERATION_TTL))
                        self._conn.execute(
                            "DELETE FROM variant_generations WHERE key IN "
                            "(SELECT key FROM variant_generations WHERE expires_at<=? LIMIT 128)", (now,))
                    self._conn.execute("COMMIT")
                    return token, row is not None
                except BaseException:
                    if self._conn.in_transaction:
                        self._conn.execute("ROLLBACK")
                    raise
            except sqlite3.Error as exc:
                raise SharedCacheUnavailable("Shared cache generation failed") from exc

    def acquire_lease(self, key, owner, ttl=LEASE_TTL):
        """Take the cross-process generation lease for ``key``.

        Returns the entry version observed at acquisition (``0`` when no
        entry exists) for fencing the later write, or ``None`` when another
        worker already holds a live lease. An expired lease may be taken
        over, so a crashed worker cannot block regeneration forever.
        """
        with self._lock:
            try:
                self._conn.execute("BEGIN IMMEDIATE")
                try:
                    now = time.time()
                    row = self._conn.execute(
                        "SELECT owner, expires_at FROM leases WHERE key = ?", (key,)
                    ).fetchone()
                    if row is not None and row[1] > now:
                        self._conn.execute("ROLLBACK")
                        return None
                    version_row = self._conn.execute(
                        "SELECT version FROM entries WHERE key = ?", (key,)
                    ).fetchone()
                    version = version_row[0] if version_row else 0
                    self._conn.execute(
                        "INSERT INTO leases (key, owner, expires_at, version) VALUES (?, ?, ?, ?)"
                        " ON CONFLICT(key) DO UPDATE SET owner=excluded.owner,"
                        " expires_at=excluded.expires_at, version=excluded.version",
                        (key, owner, now + ttl, version),
                    )
                    self._conn.execute("COMMIT")
                except BaseException:
                    if self._conn.in_transaction:
                        self._conn.execute("ROLLBACK")
                    raise
                return version
            except sqlite3.Error as exc:
                raise SharedCacheUnavailable("Shared cache lease failed") from exc

    def release_lease(self, key, owner):
        """Release a lease, but only the one this worker owns."""
        with self._lock:
            try:
                cursor = self._conn.execute(
                    "DELETE FROM leases WHERE key = ? AND owner = ?", (key, owner)
                )
                self._conn.commit()
                return cursor.rowcount > 0
            except sqlite3.Error:
                log.warning("Shared cache lease release failed for %s", key, exc_info=True)
                return False

    def owns_lease(self, key, owner):
        with self._lock:
            try:
                row = self._conn.execute("SELECT 1 FROM leases WHERE key=? AND owner=? AND expires_at>?",
                                         (key, owner, time.time())).fetchone()
                return row is not None
            except sqlite3.Error as exc:
                raise SharedCacheUnavailable("Shared cache lease lookup failed") from exc

    def close(self):
        with self._lock:
            try:
                self._conn.close()
            except sqlite3.Error:
                pass


def _is_storable(response):
    """A response with Set-Cookie or Cache-Control: private/no-store must
    never land in a cache shared between users (spec section 10.2)."""
    for name, value in response.headers:
        name = name.lower()
        if name == b"set-cookie":
            return False
        if name == b"cache-control":
            value = value.lower()
            if b"private" in value or b"no-store" in value:
                return False
    return True


class ISRCache:
    def __init__(self, cache_backend="memory", cache_path=None, namespace="", cache_url=None,
                 failure_policy=None):
        """Create an ISR cache.

        ``failure_policy`` (roadmap item B4) decides what happens when
        the shared backend (``sqlite``/``redis``) is unavailable: the
        default ``"fail_open"`` falls back to the process-local cache
        and renders locally, while ``"fail_closed"`` raises
        :class:`SharedCacheUnavailable` so the caller can answer 503
        instead of serving from degraded state. The policy is inert
        for the ``memory`` backend, which has no shared store. It
        governs the read/decision path (lookup, lease, generation);
        best-effort writes stay best-effort — see ``failure_policy``.
        """
        if cache_backend not in ("memory", "sqlite", "redis"):
            raise ValueError(
                f"Unknown cache backend {cache_backend!r}: expected 'memory', 'sqlite' or 'redis'"
            )
        self.backend_name = cache_backend
        self._cache_path = cache_path
        if cache_backend == "sqlite" and cache_path is not None:
            path = os.fspath(cache_path)
            uri_prefix = b"file:" if isinstance(path, bytes) else "file:"
            if path not in (":memory:", b":memory:") and not path.startswith(uri_prefix):
                path = os.path.abspath(path)
            self._cache_path = path
        self._cache_url = (cache_url or os.environ.get("PYNEXT_REDIS_URL")) if cache_backend == "redis" else None
        self.failure_policy = normalize_failure_policy(failure_policy, default=FAIL_OPEN)
        # The process-local store stays the native fast path in both modes:
        # the Axum server reads it directly for fresh hits.
        self.store = _native.PageCache()
        self.shared = None
        if cache_backend == "sqlite":
            if cache_path is None:
                raise ValueError("cache_path is required when cache_backend is 'sqlite'")
            self.shared = SQLiteCacheBackend(self._cache_path)
        elif cache_backend == "redis":
            from .redis_cache import RedisCacheBackend
            self.shared = RedisCacheBackend(self._cache_url)
        self._inflight = {}
        self._task_leases = {}
        self._tasks = set()
        self._variant_paths = OrderedDict()
        self._loop = None
        self._closed = False
        self.namespace = namespace

    def open(self):
        # A previous shutdown or failed app startup closes the shared store.
        # Reopening must restore it rather than silently falling back to L1.
        if self.shared is None and self.backend_name == "sqlite":
            self.shared = SQLiteCacheBackend(self._cache_path)
        elif self.shared is None and self.backend_name == "redis":
            from .redis_cache import RedisCacheBackend
            self.shared = RedisCacheBackend(self._cache_url)
        self._closed = False

    async def close(self):
        self._closed = True
        tasks = list(self._tasks)
        for task in tasks:
            task.cancel()
        if tasks:
            await asyncio.gather(*tasks, return_exceptions=True)
        self._inflight.clear()
        self._task_leases.clear()
        self._tasks.clear()
        self._variant_paths.clear()
        self._loop = None
        if self.shared is not None:
            await asyncio.to_thread(self.shared.close)
            self.shared = None

    def _check_loop(self):
        loop = asyncio.get_running_loop()
        if self._loop is None:
            self._loop = loop
        elif self._loop is not loop:
            raise RuntimeError("An ISR app instance must use a single event loop")
        return loop

    async def _shared_entry(self, key):
        """Return an entry, a miss, or a distinct backend-failure sentinel.

        Under ``fail_closed`` a backend failure raises
        :class:`SharedCacheUnavailable` instead of returning the
        sentinel, so the request fails rather than falling back.
        """
        try:
            return await asyncio.to_thread(self.shared.lookup_entry, self.namespace + key)
        except Exception as exc:
            if self.failure_policy == FAIL_CLOSED:
                raise SharedCacheUnavailable("Shared cache lookup failed") from exc
            log.warning("Shared cache lookup failed for %s", key, exc_info=True)
            return _SHARED_UNAVAILABLE

    async def _shared_store(self, key, body, policy, expected_version, owner):
        # Best-effort in both policies: the page was already rendered
        # correctly, so a failed write only loses caching, never the
        # response. See failure_policy.
        try:
            return await asyncio.to_thread(
                self.shared.insert_fenced, self.namespace + key, body,
                policy["revalidate"], policy["stale"], expected_version, owner,
            )
        except Exception:
            log.warning("Shared cache insert failed for %s", key, exc_info=True)
            return False

    async def _shared_acquire(self, key, owner):
        try:
            return await asyncio.to_thread(self.shared.acquire_lease, self.namespace + key, owner)
        except Exception as exc:
            if self.failure_policy == FAIL_CLOSED:
                raise SharedCacheUnavailable("Shared cache lease failed") from exc
            log.warning("Shared cache lease failed for %s", key, exc_info=True)
            return _SHARED_UNAVAILABLE

    async def _shared_release(self, key, owner):
        # Best-effort in both policies: leases expire on their own, and
        # a release failure must not fail a request that already rendered.
        try:
            await asyncio.to_thread(self.shared.release_lease, self.namespace + key, owner)
        except Exception:
            log.warning("Shared cache lease release failed for %s", key, exc_info=True)

    async def _shared_remove(self, key):
        try:
            return await asyncio.to_thread(self.shared.remove, self.namespace + key)
        except Exception as exc:
            if self.failure_policy == FAIL_CLOSED:
                # An explicit invalidation must not report success when
                # the shared store never saw it.
                raise SharedCacheUnavailable("Shared cache invalidation failed") from exc
            log.warning("Shared cache remove failed for %s", key, exc_info=True)
            return False

    async def invalidate(self, key):
        if self._closed:
            raise CacheBusy("ISR cache is shutting down")
        self._check_loop()
        retired = self._inflight.pop(key, None)
        removed = self.store.remove(key)
        if self.shared is not None:
            removed = await self._shared_remove(key) or removed
        return removed or retired is not None

    def _remember_variant_generation(self, path, token):
        self._variant_paths[path] = token
        self._variant_paths.move_to_end(path)
        while len(self._variant_paths) > _MAX_LOCAL_VARIANT_PATHS:
            self._variant_paths.popitem(last=False)

    async def variant_generation(self, path, *, invalidate=False):
        """Return a stable random generation, rotating it on invalidation.

        Old cache entries become unreachable even if a generation is still
        rendering, and are eventually evicted by the backend's normal TTL.
        """
        if self._closed:
            raise CacheBusy("ISR cache is shutting down")
        self._check_loop()
        had_local = path in self._variant_paths
        if self.shared is not None:
            try:
                token, existed = await asyncio.to_thread(
                    self.shared.variant_generation, self.namespace + path, invalidate=invalidate)
                self._remember_variant_generation(path, token)
                return token, existed or had_local
            except Exception as exc:
                if self.failure_policy == FAIL_CLOSED:
                    raise SharedCacheUnavailable("Shared cache generation failed") from exc
                log.warning("Shared cache generation failed for %s", path, exc_info=True)
        if invalidate or not had_local:
            token = uuid.uuid4().hex
        else:
            token = self._variant_paths[path]
        self._remember_variant_generation(path, token)
        return token, had_local

    def _register(self, key, task, owner=None):
        self._inflight[key] = task
        self._task_leases[task] = owner
        self._tasks.add(task)

        def completed(finished):
            self._tasks.discard(finished)
            self._task_leases.pop(finished, None)
            if self._inflight.get(key) is finished:
                self._inflight.pop(key, None)
            if not finished.cancelled():
                error = finished.exception()
                if error is not None:
                    log.error("ISR regeneration failed for %s", key,
                              exc_info=(type(error), error, error.__traceback__))
        task.add_done_callback(completed)
        return task

    async def _wait_for_shared(self, key, timeout):
        """Wait for another worker's first generation to land in the shared
        cache. Returns the fresh body, or None on timeout. If the other
        worker's lease expires while we wait, take the lease and report
        the observed version so the caller becomes the generator."""
        deadline = time.monotonic() + timeout
        owner = f"{os.getpid()}:{uuid.uuid4().hex}"
        while True:
            entry = await self._shared_entry(key)
            if entry is _SHARED_UNAVAILABLE:
                return ("unavailable", None)
            if entry is not None and entry.status == "fresh":
                return ("fresh", entry)
            if time.monotonic() >= deadline:
                return ("timeout", None)
            version = await self._shared_acquire(key, owner)
            if version is _SHARED_UNAVAILABLE:
                return ("unavailable", None)
            if version is not None:
                return ("lease", (version, owner))
            await asyncio.sleep(LEASE_WAIT_INTERVAL)

    async def get_or_render(self, key, policy, render):
        loop = asyncio.get_running_loop()
        if self._closed:
            raise CacheBusy("ISR cache is shutting down")
        if self._loop is None:
            self._loop = loop
        elif self._loop is not loop:
            raise RuntimeError("An ISR app instance must use a single event loop")
        status, body = self.store.lookup(key)
        if status == "fresh" and self.shared is None:
            return body
        if self.shared is None:
            return await self._get_or_render_local(key, policy, render, status, body)
        return await self._get_or_render_shared(key, policy, render, status, body)

    async def _generate(self, key, policy, render, lease=None):
        """Render once and store the result, fenced by the lease version.

        ``lease`` is ``(expected_version, owner)`` for a shared-cache
        generation that holds the cross-process lease. A fallback without a
        lease is stored only locally. A fenced-out generation still serves
        its own caller, but cannot replace either cache layer.
        """
        owner = lease[1] if lease is not None else None
        expected_version = lease[0] if lease is not None else None
        try:
            async with asyncio.timeout(GENERATION_TIMEOUT):
                if lease is not None:
                    # Another worker may have populated the cache after our
                    # miss but before we obtained the now-free lease. Check
                    # again while holding the lease before rendering.
                    entry = await self._shared_entry(key)
                    if entry is not _SHARED_UNAVAILABLE and entry is not None and entry.status == "fresh":
                        if self._inflight.get(key) is asyncio.current_task():
                            self.store.insert(key, entry.body, entry.fresh_remaining, entry.stale_remaining)
                        return entry.body
                response = await render()
                if response.status != 200:
                    raise ValueError("ISR can cache only successful page responses")
                # An invalidated generation may finish for existing callers,
                # but must never repopulate the cache after invalidation.
                if self._inflight.get(key) is asyncio.current_task():
                    if _is_storable(response):
                        shared_stored = True
                        if self.shared is not None and owner is not None:
                            shared_stored = await self._shared_store(key, response.body, policy, expected_version, owner)
                            if not shared_stored:
                                log.warning("Shared ISR insert for %s failed or was fenced out;"
                                            " page was served but not cached", key)
                        # Do not populate L1 after a shared write was rejected
                        # or after this app invalidated the running task.
                        if shared_stored and self._inflight.get(key) is asyncio.current_task():
                            if not self.store.insert(key, response.body, policy["revalidate"], policy["stale"]):
                                log.warning("ISR cache insert failed for %s; page was served but not cached", key)
                    else:
                        log.info("ISR response for %s is private; served but not cached", key)
                return response.body
        finally:
            if owner is not None and self.shared is not None:
                await self._shared_release(key, owner)

    async def _get_or_render_local(self, key, policy, render, status, body):
        task = self._inflight.get(key)
        if task is None and len(self._tasks) < MAX_INFLIGHT:
            task = self._register(key, asyncio.create_task(
                self._generate(key, policy, render), context=contextvars.Context()))
        if status == "stale":
            return body
        if task is None:
            raise CacheBusy("Too many ISR generations")
        # A cancelled request must not cancel the shared render for other callers.
        return await asyncio.shield(task)

    async def _get_or_render_shared(self, key, policy, render, status, body):
        entry = await self._shared_entry(key)
        if entry is _SHARED_UNAVAILABLE:
            if status == "fresh":
                return body
            return await self._get_or_render_local(key, policy, render, status, body)
        if entry is not None and entry.status == "fresh":
            # Keep a local fallback for shared-store outages. Shared mode
            # still validates each hit against the authoritative store.
            self.store.insert(key, entry.body, entry.fresh_remaining, entry.stale_remaining)
            return entry.body
        task = self._inflight.get(key)
        if task is not None:
            owner = self._task_leases.get(task)
            try:
                valid = owner is not None and await asyncio.to_thread(
                    self.shared.owns_lease, self.namespace + key, owner)
            except Exception as exc:
                if self.failure_policy == FAIL_CLOSED:
                    raise SharedCacheUnavailable("Shared cache lease lookup failed") from exc
                if status == "fresh":
                    return body
                return await self._get_or_render_local(key, policy, render, status, body)
            if not valid:
                if self._inflight.get(key) is task:
                    self._inflight.pop(key, None)
                task = None
        if entry is None or entry.status == "expired":
            self.store.remove(key)
        if task is None and len(self._tasks) < MAX_INFLIGHT:
            if entry is not None and entry.status == "stale":
                # Serve stale now; regenerate in the background, but only
                # the worker that wins the cross-process lease renders.
                owner = f"{os.getpid()}:{uuid.uuid4().hex}"
                version = await self._shared_acquire(key, owner)
                if version is _SHARED_UNAVAILABLE:
                    return await self._get_or_render_local(key, policy, render, "stale", entry.body)
                if version is not None:
                    task = self._register(key, asyncio.create_task(
                        self._generate(key, policy, render, lease=(version, owner)),
                        context=contextvars.Context()), owner)
                return entry.body
            # First generation (or expired): become the generator if the
            # lease is free, otherwise wait for the worker that holds it.
            owner = f"{os.getpid()}:{uuid.uuid4().hex}"
            version = await self._shared_acquire(key, owner)
            if version is _SHARED_UNAVAILABLE:
                return await self._get_or_render_local(key, policy, render, status, body)
            if version is not None:
                task = self._register(key, asyncio.create_task(
                    self._generate(key, policy, render, lease=(version, owner)),
                    context=contextvars.Context()), owner)
            else:
                outcome, payload = await self._wait_for_shared(key, GENERATION_TIMEOUT)
                if outcome == "fresh":
                    entry = payload
                    self.store.insert(key, entry.body, entry.fresh_remaining, entry.stale_remaining)
                    return entry.body
                if outcome == "lease":
                    version, owner = payload
                    task = self._register(key, asyncio.create_task(
                        self._generate(key, policy, render, lease=(version, owner)),
                        context=contextvars.Context()), owner)
                else:
                    # The other worker is still generating after the wait.
                    # Render locally rather than failing the request, but
                    # never write to the shared store without a lease.
                    if outcome == "timeout":
                        log.warning("ISR first generation for %s is still running in another worker;"
                                    " rendering locally", key)
                    task = self._register(key, asyncio.create_task(
                        self._generate(key, policy, render),
                        context=contextvars.Context()))
        if entry is not None and entry.status == "stale":
            return entry.body
        if task is None:
            raise CacheBusy("Too many ISR generations")
        # A cancelled request must not cancel the shared render for other callers.
        return await asyncio.shield(task)
