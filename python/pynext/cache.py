class ISRCache:
    def __init__(self, cache_backend="memory", cache_path=None, namespace="", cache_url=None,
                 failure_policy=None, sqlite_max_entries=None, sqlite_max_bytes=None, cache_handler=None,
                 health=None, metrics=None):
        """Create an ISR cache.

        ``failure_policy`` (roadmap item B4) decides what happens when
        the shared backend (``sqlite``/``filesystem``/``redis``) is unavailable: the
        default ``"fail_open"`` falls back to the process-local cache
        and renders locally, while ``"fail_closed"`` raises
        :class:`SharedCacheUnavailable` so the caller can answer 503
        instead of serving from degraded state. The policy is inert
        for the ``memory`` backend, which has no shared store. It
        governs the read/decision path (lookup, lease, generation);
        best-effort writes stay best-effort — see ``failure_policy``.

        ``sqlite_max_entries`` / ``sqlite_max_bytes`` tune the SQLite
        backend's capacity caps (``None`` selects the backend defaults,
        currently 10,000 entries / 128 MiB); they are ignored for the
        other backends.

        ``cache_handler`` selects the cache store through the
        :class:`CacheHandler` plugin contract instead of the
        ``cache_backend`` name: a registered name (``"memory"``,
        ``"sqlite"``, ``"redis"`` or a custom one), a factory called
        as ``factory(cache_path=None, cache_url=None)``, or a handler
        instance. A :class:`SharedCacheHandler` is used directly for
        cross-process coordination; a plain :class:`CacheHandler` is
        wrapped so reads/writes go through it while generation is
        coordinated only within this process. When ``cache_handler``
        is given, ``cache_backend`` is ignored.

        ``health`` is an optional :class:`observability.BackendHealth`
        that the read/decision path reports to whenever it actually
        touches the shared backend (success or failure), so ``/readyz``
        can reflect backend health from last-seen state without
        probing. Best-effort writes do not report.

        ``metrics`` is an optional :class:`observability.MetricsCollector`
        that counts failure-policy activations (``"refused"`` under
        ``fail_closed``, ``"degraded"`` under ``fail_open``).
        """
        self.handler = None
        self._shared_builder = None
        if cache_handler is not None:
            factory = None
            instance = None
            if isinstance(cache_handler, str):
                try:
                    factory = get_cache_handler_factory(cache_handler)
                except KeyError as exc:
                    raise ValueError(
                        f"Unknown cache handler {cache_handler!r}: expected one of "
                        f"{', '.join(list_cache_handlers())}") from exc
            elif isinstance(cache_handler, CacheHandler):
                instance = cache_handler
            elif callable(cache_handler):
                factory = cache_handler
            else:
                raise TypeError(
                    "cache_handler must be a registered name, a factory, or a CacheHandler")

            def _build_shared():
                handler = (factory(cache_path=cache_path, cache_url=cache_url)
                           if factory is not None else instance)
                return self._wrap_handler(handler)

            self._shared_builder = _build_shared
            self.shared = _build_shared()
            self._sync_handler()
            self.backend_name = getattr(self.handler, "name", "custom") or "custom"
            self._cache_path = cache_path
            self._cache_url = cache_url
            self.failure_policy = normalize_failure_policy(failure_policy, default=FAIL_OPEN)
            # Same reporting hooks as the cache_backend path below: the
            # shared store is touched here too, so _report_backend and
            # _report_degraded (and the warmup CacheSignal) must exist.
            self._health = health
            self._metrics = metrics
            self.signal = CacheSignal()
            # The process-local store stays the native fast path in both modes:
            # the Axum server reads it directly for fresh hits.
            self.store = _native.PageCache()
            self._inflight = {}
            self._task_leases = {}
            self._tasks = set()
            # In-flight shared writes, keyed by cache key (Next.js ``pendingSets``):
            # a second write for the same key waits on the event instead of
            # issuing a duplicate write, and a read waits (bounded) and re-reads
            # the shared entry once the write lands.
            self._pending_sets = {}
            self._variant_paths = OrderedDict()
            # Tag invalidation state (same as the cache_backend path below):
            # ``_key_tags`` / ``_key_generated_at`` record which tags each
            # cached key carries and when its current entry was generated,
            # so a tag invalidation can retire in-flight generations and
            # reclassify process-local hits without consulting the backend.
            self._tag_manifest = {}
            self._key_tags = OrderedDict()
            self._key_generated_at = OrderedDict()
            self._cached_paths = OrderedDict()
            self._loop = None
            self._closed = False
            self.namespace = namespace
            return
        if cache_backend not in ("memory", "sqlite", "redis", "filesystem"):            raise ValueError(
                "Unknown cache backend {!r}: expected 'memory', 'sqlite', 'redis' or 'filesystem'".format(cache_backend)
            )
        self.backend_name = cache_backend
        self._cache_path = cache_path
        self._sqlite_max_entries = sqlite_max_entries
        self._sqlite_max_bytes = sqlite_max_bytes
        if cache_backend == "sqlite" and cache_path is not None:
            path = os.fspath(cache_path)
            uri_prefix = b"file:" if isinstance(path, bytes) else "file:"
            if path not in (":memory:", b":memory:") and not path.startswith(uri_prefix):
                path = os.path.abspath(path)
            self._cache_path = path
        self._cache_url = (cache_url or os.environ.get("PYNEXT_REDIS_URL")) if cache_backend == "redis" else None
        self.failure_policy = normalize_failure_policy(failure_policy, default=FAIL_OPEN)
        self._health = health
        self._metrics = metrics
        # The process-local store stays the native fast path in both modes:
        # the Axum server reads it directly for fresh hits.
        self.store = _native.PageCache()
        self.shared = None
        if cache_backend == "sqlite":
            if cache_path is None:
                raise ValueError("cache_path is required when cache_backend is 'sqlite'")
            self.shared = SQLiteCacheBackend(
                self._cache_path, max_entries=sqlite_max_entries, max_bytes=sqlite_max_bytes)
            self.shared = SQLiteCacheBackend(self._cache_path)
        elif cache_backend == "filesystem":
            if cache_path is None:
                raise ValueError("cache_path is required when cache_backend is 'filesystem'")
            self.shared = FileSystemCacheBackend(self._cache_path)
        elif cache_backend == "redis":
            from .redis_cache import RedisCacheBackend
            self.shared = RedisCacheBackend(self._cache_url)
        self._inflight = {}
        self._task_leases = {}
        self._tasks = set()
        # C-2 retention: ``_retained`` maps a key to its last-known-good
        # ``(body, retained_at)`` — the previous entry a failed
        # regeneration falls back to, even after the backends have
        # dropped the expired entry itself. ``_regen_failures`` maps a
        # key to ``{"failures", "next_retry_at", "last_error"}`` for the
        # retry backoff. Both are process-local: another worker keeps
        # its own copies and learns of invalidations through the shared
        # tag manifest (see :meth:`_retained_body`).
        self._retained = OrderedDict()
        self._retained_bytes = 0
        self._regen_failures = {}
        # In-flight shared writes, keyed by cache key (Next.js ``pendingSets``):
        # a second write for the same key waits on the event instead of
        # issuing a duplicate write, and a read waits (bounded) and re-reads
        # the shared entry once the write lands.
        self._pending_sets = {}
        # CacheSignal (Next.js cache-signal.ts): counts in-flight
        # generations so warmup and cross-worker waits can tell when
        # cache reads have settled without polling. Every task added by
        # _register brackets one read; see its done callback.
        self.signal = CacheSignal()
        self._variant_paths = OrderedDict()
        # Tag invalidation state. ``_tag_manifest`` is the process-local
        # copy of the tag manifest (authoritative for the memory backend;
        # shared backends keep their own copy in the shared store).
        # ``_key_tags`` / ``_key_generated_at`` record which tags each
        # cached key carries and when its current entry was generated,
        # so a tag invalidation can retire in-flight generations and
        # reclassify process-local hits without consulting the backend.
        self._tag_manifest = {}
        self._key_tags = OrderedDict()
        self._key_generated_at = OrderedDict()
        self._cached_paths = OrderedDict()
        self._loop = None
        self._closed = False
        self.namespace = namespace

    @staticmethod
    def _wrap_handler(handler):
        """Validate ``handler`` and adapt it to the shared-cache role."""
        _validate_cache_handler(handler)
        handler.open()
        if isinstance(handler, SharedCacheHandler):
            return handler
        return _PlainHandlerSharedAdapter(handler)

    def _sync_handler(self):
        """Point ``self.handler`` at the handler behind ``self.shared``."""
        if isinstance(self.shared, _PlainHandlerSharedAdapter):
            self.handler = self.shared.handler
        else:
            self.handler = self.shared

    def open(self):
        # A previous shutdown or failed app startup closes the shared store.
        # Reopening must restore it rather than silently falling back to L1.
        if self._shared_builder is not None:
            if self.shared is None:
                self.shared = self._shared_builder()
                self._sync_handler()
            self._closed = False
            return
        if self.shared is None and self.backend_name == "sqlite":
            self.shared = SQLiteCacheBackend(
                self._cache_path, max_entries=self._sqlite_max_entries,
                max_bytes=self._sqlite_max_bytes)
            self.shared = SQLiteCacheBackend(self._cache_path)
        elif self.shared is None and self.backend_name == "filesystem":
            self.shared = FileSystemCacheBackend(self._cache_path)
        elif self.shared is None and self.backend_name == "redis":
            from .redis_cache import RedisCacheBackend
            self.shared = RedisCacheBackend(self._cache_url)
        self._closed = False

    async def wait_for_background(self, timeout):
        """Wait for background ISR regenerations to finish (C-P2-5).

        Returns True when no background task is left, False on timeout.
        Tasks still running after ``timeout`` are left alone here;
        :meth:`close` cancels them, so shutdown stays bounded. A
        regeneration that finishes in time publishes its result
        normally, instead of being cancelled mid-render for no reason.
        """
        deadline = time.monotonic() + max(0.0, timeout)
        while True:
            tasks = [task for task in list(self._tasks) if not task.done()]
            if not tasks:
                return True
            remaining = deadline - time.monotonic()
            if remaining <= 0:
                return False
            await asyncio.wait(tasks, timeout=remaining,
                               return_when=asyncio.FIRST_COMPLETED)

    async def close(self, executor=None):
        """Cancel in-flight generations and close the shared backend.

        ``executor`` is the thread pool the blocking ``shared.close()``
        runs on. Callers pass the app's exit executor (C-P1-3c) so cache
        teardown never waits behind the sync entry limiter; ``None`` keeps
        the loop's default executor, as before.
        """
        self._closed = True
        tasks = list(self._tasks)
        for task in tasks:
            task.cancel()
        if tasks:
            await asyncio.gather(*tasks, return_exceptions=True)
        self._inflight.clear()
        self._task_leases.clear()
        self._tasks.clear()
        self._retained.clear()
        self._retained_bytes = 0
        self._regen_failures.clear()
        for event in self._pending_sets.values():
            event.set()
        self._pending_sets.clear()
        self._variant_paths.clear()
        self._key_tags.clear()
        self._key_generated_at.clear()
        self._cached_paths.clear()
        self._loop = None
        if self.shared is not None:
            if executor is None:
                await asyncio.to_thread(self.shared.close)
            else:
                await run_sync_with_context(self.shared.close, executor=executor)
            self.shared = None

    def _check_loop(self):
        loop = asyncio.get_running_loop()
        if self._loop is None:
            self._loop = loop
        elif self._loop is not loop:
            raise RuntimeError("An ISR app instance must use a single event loop")
        return loop

    def _report_backend(self, healthy):
        """Record a shared-backend touch for ``/readyz`` (no-op without one)."""
        if self._health is not None and self.shared is not None:
            self._health.report("isr-cache", healthy=healthy, policy=self.failure_policy)

    def _report_degraded(self):
        """Count one failure-policy activation (refused vs degraded)."""
        if self._metrics is not None and self.shared is not None:
            outcome = "refused" if self.failure_policy == FAIL_CLOSED else "degraded"
            self._metrics.observe_degraded("isr-cache", self.failure_policy, outcome)

    async def _shared_entry(self, key):
        """Return an entry, a miss, or a distinct backend-failure sentinel.

        Under ``fail_closed`` a backend failure raises
        :class:`SharedCacheUnavailable` instead of returning the
        sentinel, so the request fails rather than falling back.
        """
        try:
            entry = await asyncio.to_thread(self.shared.lookup_entry, self.namespace + key)
        except Exception as exc:
            self._report_backend(False)
            self._report_degraded()
            if self.failure_policy == FAIL_CLOSED:
                raise SharedCacheUnavailable("Shared cache lookup failed") from exc
            log.warning("Shared cache lookup failed for %s", key, exc_info=True)
            return _SHARED_UNAVAILABLE
        self._report_backend(True)
        return entry

    async def _shared_store(self, key, body, policy, expected_version, owner, tags=(),
                            generated_at=None, generated_mono=None):
        # Best-effort in both policies: the page was already rendered
        # correctly, so a failed write only loses caching, never the
        # response. See failure_policy.
        #
        # ``generated_at`` / ``generated_mono`` stamp the entry with the
        # render *start* time (see :meth:`_generate`): a generation that
        # started before a tag invalidation but stored after it must be
        # judged by when its content was produced, not when it landed.
        try:
            # Entry tags are namespaced like keys: the tag manifest
            # records invalidations under ``namespace + tag`` (see
            # :meth:`revalidate_tag`), so stored tags must carry the
            # same prefix or a cross-worker invalidation never matches
            # them on lookup.
            namespaced_tags = [self.namespace + tag for tag in tags]
            return await asyncio.to_thread(
                self.shared.insert_fenced, self.namespace + key, body,
                policy["revalidate"], policy["stale"], expected_version, owner,
                namespaced_tags, generated_at, generated_mono,
            )
        except Exception:
            log.warning("Shared cache insert failed for %s", key, exc_info=True)
            return False

    async def _shared_acquire(self, key, owner):
        try:
            acquired = await asyncio.to_thread(self.shared.acquire_lease, self.namespace + key, owner)
        except Exception as exc:
            self._report_backend(False)
            self._report_degraded()
            if self.failure_policy == FAIL_CLOSED:
                raise SharedCacheUnavailable("Shared cache lease failed") from exc
            log.warning("Shared cache lease failed for %s", key, exc_info=True)
            return _SHARED_UNAVAILABLE
        self._report_backend(True)
        return acquired

    async def _shared_release(self, key, owner):
        # Best-effort in both policies: leases expire on their own, and
        # a release failure must not fail a request that already rendered.
        try:
            await asyncio.to_thread(self.shared.release_lease, self.namespace + key, owner)
        except Exception:
            log.warning("Shared cache lease release failed for %s", key, exc_info=True)

    async def _shared_remove(self, key):
        try:
            removed = await asyncio.to_thread(self.shared.remove, self.namespace + key)
        except Exception as exc:
            self._report_backend(False)
            self._report_degraded()
            if self.failure_policy == FAIL_CLOSED:
                # An explicit invalidation must not report success when
                # the shared store never saw it.
                raise SharedCacheUnavailable("Shared cache invalidation failed") from exc
            log.warning("Shared cache remove failed for %s", key, exc_info=True)
            return False
        self._report_backend(True)
        return removed


    def _store_insert(self, key, body, fresh_seconds, stale_seconds):
        """Insert into the process-local L1, clamping to its native cap.

        The native PageCache accepts at most ``_MAX_L1_SECONDS`` per
        window (see ``crates/pynext-native/src/lib.rs``) and raises
        ValueError beyond it, while ISR policies run to
        ``MAX_CACHE_SECONDS``; clamp so a long-lived entry still caches
        locally for a week instead of failing the request. Returns False
        when the entry cannot be stored. A successful insert also
        remembers the body as the key's last-known-good value (C-2
        retention), so a later failed regeneration can still serve it
        after the backends have dropped the expired entry itself.
        """
        try:
            fresh = min(float(fresh_seconds), _MAX_L1_SECONDS)
            stale = min(float(stale_seconds), _MAX_L1_SECONDS)
        except (TypeError, ValueError):
            return False
        try:
            stored = self.store.insert(key, body, fresh, stale)
        except ValueError:
            return False
        if stored:
            self._retain(key, body)
        return stored

    def _retain(self, key, body, retained_at=None):
        """Remember ``body`` as the last-known-good value for ``key``.

        Best-effort and bounded: the oldest retained entries are
        evicted once the count or byte cap is reached. Only bodies
        stored through the render path are retained — entries seeded
        directly into the backend (tests, the native fast path) have no
        retained copy, so a failed regeneration for them still errors
        instead of serving a value this layer never saw.
        """
        if not isinstance(body, (bytes, bytearray)):
            return
        body = bytes(body)
        previous = self._retained.get(key)
        if previous is not None:
            self._retained_bytes -= len(previous[0])
        self._retained[key] = (body, time.time() if retained_at is None else retained_at)
        self._retained.move_to_end(key)
        self._retained_bytes += len(body)
        while ((len(self._retained) > _MAX_RETAINED_ENTRIES
                or self._retained_bytes > _MAX_RETAINED_BYTES)
               and self._retained):
            old_key, old_body = self._retained.popitem(last=False)
            self._retained_bytes -= len(old_body[0])

    def _drop_retained(self, key):
        """Forget the retained previous value for ``key``, if any."""
        record = self._retained.pop(key, None)
        if record is not None:
            self._retained_bytes -= len(record[0])

    async def _retained_body(self, key, tags=()):
        """Return the retained previous body for ``key``, or ``None``.

        The copy is void when an explicit invalidation landed after it
        was retained: a same-worker invalidation already drops it (see
        :meth:`_apply_tag_invalidation` and :meth:`invalidate`), and a
        cross-worker tag invalidation is caught here through the shared
        tag manifest — a tag whose ``expired_at`` passed after the copy
        was retained means the content was invalidated, so retention
        must not resurrect it. Time-based expiry never voids a copy:
        that is exactly what retention is for.
        """
        record = self._retained.get(key)
        if record is None:
            return None
        body, retained_at = record
        if self.shared is not None:
            check_tags = tuple(tags) or tuple(self._key_tags.get(key, ()))
            if check_tags:
                try:
                    times = await asyncio.to_thread(
                        self.shared.get_tag_times,
                        [self.namespace + tag for tag in check_tags])
                except Exception:
                    times = {}
                now = time.time()
                for tag in check_tags:
                    _, expired_at = times.get(self.namespace + tag, (None, None))
                    if expired_at is not None and retained_at < expired_at <= now:
                        self._drop_retained(key)
                        return None
        return body

    async def retained_body(self, key, tags=()):
        """Return the retained last-known-good body for ``key``, or ``None``.

        Public wrapper for :meth:`_retained_body` for callers outside the
        cache (the app's ISR handler serves it when regeneration cannot
        even start, e.g. :class:`CacheBusy`). ``tags`` defaults to the
        tags remembered for the key when omitted.
        """
        return await self._retained_body(key, tags)

    def _record_regen_failure(self, key, exc):
        """Record a failed regeneration and arm the retry backoff.

        Consecutive failures for ``key`` count up; the next retry is
        due after :func:`regen_retry_delay` seconds. The previous entry
        is deliberately left in place — a failed regeneration never
        evicts it (Next.js ``retainPreviousCacheEntry``).
        """
        record = self._regen_failures.get(key)
        failures = (record["failures"] + 1) if record is not None else 1
        delay = regen_retry_delay(failures)
        self._regen_failures[key] = {
            "failures": failures,
            "next_retry_at": time.monotonic() + delay,
            "last_error": f"{type(exc).__name__}: {exc}",
        }
        log.warning("ISR regeneration failed for %s (consecutive failure %d);"
                    " retaining previous entry, next retry in %.1fs",
                    key, failures, delay)

    def _clear_regen_failure(self, key):
        """Clear the failure/backoff record after a successful regeneration."""
        self._regen_failures.pop(key, None)

    def _regen_backoff_remaining(self, key):
        """Seconds until a failed regeneration for ``key`` may be retried (0 if none)."""
        record = self._regen_failures.get(key)
        if record is None:
            return 0.0
        return max(0.0, record["next_retry_at"] - time.monotonic())

    def _remember_key_tags(self, key, tags):
        self._key_tags[key] = tuple(tags)
        self._key_tags.move_to_end(key)
        while len(self._key_tags) > _MAX_LOCAL_VARIANT_PATHS:
            old_key, _ = self._key_tags.popitem(last=False)
            self._key_generated_at.pop(old_key, None)

    def _local_tag_status(self, key):
        """Classify a process-local entry by its tags.

        Mirrors the shared backends' manifest check: ``"expired"``
        when any tag was invalidated after the entry was generated and
        that invalidation has fully expired, ``"stale"`` when any tag
        was invalidated after generation but the entry is still inside
        the stale window, ``"fresh"`` otherwise. Entries with no
        recorded tags or generation time are unaffected.
        """
        tags = self._key_tags.get(key)
        generated_at = self._key_generated_at.get(key)
        if not tags or generated_at is None:
            return "fresh"
        now = time.time()
        stale = False
        for tag in tags:
            record = self._tag_manifest.get(tag)
            if record is None:
                continue
            stale_at, expired_at = record
            if generated_at < expired_at <= now:
                return "expired"
            if stale_at > generated_at:
                stale = True
        return "stale" if stale else "fresh"

    def _apply_tag_invalidation(self, tag, expire):
        """Record ``tag`` in the process-local manifest and evict or
        retire matching local entries.

        Returns the number of local entries evicted plus in-flight
        generations retired. A deferred ``expire`` (greater than zero)
        demotes entries to stale instead of evicting them, so it retires
        only in-flight generations. ``expire=None`` and ``expire=0`` both
        expire entries immediately — they record the identical manifest
        row — so both evict matching entries from the local store; the
        native (Axum) fast path serves the local store directly without
        a tag check, so leaving an immediately-expired entry there
        would keep serving it as fresh. Shared backends record the same
        invalidation in their own manifest; this only touches
        process-local state.
        """
        now = time.time()
        self._tag_manifest[tag] = (now, now if expire is None else now + expire)
        # The process-local manifest is the memory backend's copy of the
        # tag manifest; without pruning it grows with every distinct tag
        # (for example per-user tags) and is never cleaned. Mirror the
        # SQLite backend's opportunistic prune: a record can only affect
        # entries generated before its expired_at, and no entry lives
        # longer than fresh+stale (2 * MAX_CACHE_SECONDS), so older rows
        # are dead weight.
        cutoff = now - 2 * MAX_CACHE_SECONDS
        for old_tag in [t for t, (_, expired_at) in self._tag_manifest.items()
                        if expired_at < cutoff]:
            del self._tag_manifest[old_tag]
        evicted = 0
        for key, tags in list(self._key_tags.items()):
            if tag in tags:
                if self._inflight.pop(key, None) is not None:
                    evicted += 1
                if (expire is None or expire == 0) and self.store.remove(key):
                    evicted += 1
                # An explicit invalidation voids the retained previous
                # value too — even a deferred one: the stale body is
                # still served from the store while the window runs,
                # but once it lapses the invalidated content must not
                # come back through the retention fallback (C-2 covers
                # time-based expiry only, never explicit invalidation).
                self._drop_retained(key)
        return evicted

    async def revalidate_tag(self, tag, expire=None):
        """Invalidate every cached entry carrying ``tag``.

        ``expire=None`` (or ``0``) expires matching entries immediately;
        a positive ``expire`` keeps them merely stale (served once more
        while a regeneration runs in the background) until that delay
        passes.
        Entries generated after this call are unaffected. Generations
        already in flight for a matching key are retired so they cannot
        refill the cache with pre-invalidation content. With a shared
        backend the record is stored there, so other workers see it;
        with the memory backend it is process-local. Returns True when
        the invalidation was recorded.
        """
        tag = _validate_invalidation_tag(tag)
        expire = _validate_tag_expire(expire)
        if self._closed:
            raise CacheBusy("ISR cache is shutting down")
        self._check_loop()
        self._apply_tag_invalidation(tag, expire)
        if self.shared is None:
            return True
        try:
            return await asyncio.to_thread(
                self.shared.revalidate_tag, self.namespace + tag, expire)
        except Exception as exc:
            if self.failure_policy == FAIL_CLOSED:
                raise SharedCacheUnavailable("Shared cache tag invalidation failed") from exc
            log.warning("Shared cache tag invalidation failed for %s", tag, exc_info=True)
            return False

    async def invalidate_tag(self, tag, *, expire=None):
        """Invalidate every cached entry carrying ``tag`` (on-demand).

        Same recording as :meth:`revalidate_tag`, but returns the number
        of entries evicted from this worker's local cache (stored entries
        plus generations retired mid-render) instead of a boolean.
        Entries held by other workers are caught by the shared tag
        manifest on their next lookup, so the count is a local lower
        bound, not a global total. A deferred ``expire`` (greater than
        zero) demotes entries to stale instead of evicting them, so it
        returns 0 for stored entries (in-flight generations are still
        retired).
        """
        tag = _validate_invalidation_tag(tag)
        expire = _validate_tag_expire(expire)
        if self._closed:
            raise CacheBusy("ISR cache is shutting down")
        self._check_loop()
        evicted = self._apply_tag_invalidation(tag, expire)
        if self.shared is not None:
            try:
                await asyncio.to_thread(
                    self.shared.revalidate_tag, self.namespace + tag, expire)
            except Exception as exc:
                if self.failure_policy == FAIL_CLOSED:
                    raise SharedCacheUnavailable("Shared cache tag invalidation failed") from exc
                log.warning("Shared cache tag invalidation failed for %s", tag, exc_info=True)
        return evicted

    async def _wait_pending_set(self, key, timeout):
        """Wait for the in-flight shared write for ``key`` to finish.

        Returns True when the write completed within ``timeout`` (whether
        it stored a body or not), False on timeout or when no write was
        pending.
        """
        event = self._pending_sets.get(key)
        if event is None:
            return False
        try:
            await asyncio.wait_for(event.wait(), timeout)
            return True
        except TimeoutError:
            return False

    def _finish_pending_set(self, key, event):
        # Resolve waiters first, then drop the registration — but only
        # when it is still ours, so a newer set for the same key is never
        # unregistered by an older one finishing (the Next.js ``finally``
        # deletes blindly).
        event.set()
        if self._pending_sets.get(key) is event:
            del self._pending_sets[key]

    async def _await_pending_set(self, key):
        """If a shared write for ``key`` is in flight, wait for it (bounded)
        and re-read the shared entry.

        Returns the re-read entry, or None when no write was pending, the
        wait timed out, or the backend failed — the caller then keeps its
        previous entry and falls back to the pre-existing path.
        """
        if key not in self._pending_sets:
            return None
        if not await self._wait_pending_set(key, timeout=PENDING_SET_GET_TIMEOUT):
            return None
        entry = await self._shared_entry(key)
        if entry is _SHARED_UNAVAILABLE:
            return None
        return entry

    async def _store_shared(self, key, body, policy, expected_version, owner, tags=(),
                            generated_at=None, generated_mono=None):
        """Store ``body`` in the shared backend, coalescing concurrent sets
        for the same key (Next.js ``pendingSets``).

        Returns ``(stored, coalesced)``. When another set for ``key`` is
        already in flight, this waits for it (bounded) and re-reads the
        shared entry: if it is fresh the earlier set already stored a
        usable body, so this write is skipped and the local cache is
        populated from the shared entry instead (``coalesced=True``). When
        no set is in flight this registers one before writing and resolves
        it in a ``finally``, so a concurrent ``get`` waits for the write
        instead of reading the previous version. A failed or fenced-out
        write resolves its waiters just the same — a pending set must never
        block readers forever.
        """
        deadline = time.monotonic() + PENDING_SET_WAIT_TIMEOUT
        while True:
            pending = self._pending_sets.get(key)
            if pending is None:
                break
            remaining = deadline - time.monotonic()
            if remaining <= 0 or not await self._wait_pending_set(key, timeout=remaining):
                break
            entry = await self._shared_entry(key)
            if entry is _SHARED_UNAVAILABLE:
                break
            if entry is not None and entry.status == "fresh":
                self.store.insert(key, entry.body, entry.fresh_remaining, entry.stale_remaining)
                return True, True
            # The earlier set finished without leaving a fresh entry
            # (failed, fenced out, or private); loop and register our own
            # set — another set may have started while we re-read.
        event = asyncio.Event()
        self._pending_sets[key] = event
        try:
            return await self._shared_store(key, body, policy, expected_version, owner, tags,
                                          generated_at=generated_at,
                                          generated_mono=generated_mono), False
        finally:
            self._finish_pending_set(key, event)

    async def invalidate(self, key):
        """Remove ``key`` from the local cache and, when configured, the shared store.

        Returns ``True`` when a local or shared entry was removed, or an
        in-flight generation was retired. In ``fail_open`` mode shared
        removal is best-effort: local removal or retirement can return
        ``True`` even when the shared store is unavailable, so ``True``
        does not guarantee the shared entry is gone — when the
        shared store is unreachable the removal is skipped (and logged)
        and other workers may keep serving the stale entry until it
        expires or the store recovers. In ``fail_closed`` mode a
        shared-removal failure raises :class:`SharedCacheUnavailable`
        instead of returning ``True``, so callers never mistake an
        unapplied invalidation for a completed one. With no shared
        backend (``memory``), invalidation is process-local.
        """
        if self._closed:
            raise CacheBusy("ISR cache is shutting down")
        self._check_loop()
        retired = self._inflight.pop(key, None)
        self._cached_paths.pop(key, None)
        removed = self.store.remove(key)
        self._key_tags.pop(key, None)
        self._key_generated_at.pop(key, None)
        # An explicit invalidation voids the retained previous value
        # and any retry backoff: the next request regenerates from
        # scratch instead of serving invalidated content (C-2 retention
        # covers time-based expiry only).
        self._drop_retained(key)
        self._regen_failures.pop(key, None)
        if self.shared is not None:
            removed = await self._shared_remove(key) or removed
        return removed or retired is not None

    def _remember_cached_path(self, key):
        self._cached_paths[key] = None
        self._cached_paths.move_to_end(key)
        while len(self._cached_paths) > _MAX_CACHED_PATHS:
            self._cached_paths.popitem(last=False)

    async def cached_keys(self):
        """Return the concrete ISR paths this cache knows about, sorted.

        The union of this process's rendered paths (including the
        variant-generation paths of query-variant pages, whose cache keys
        are hashed) and the shared backend's stored keys, with the
        namespace prefix stripped and internal ``\\0isr:`` hashed keys
        dropped. Under ``fail_open`` a shared-backend listing failure
        falls back to the process-local paths (and logs); under
        ``fail_closed`` it raises :class:`SharedCacheUnavailable`, so a
        scoped revalidation never reports success it did not check.
        """
        if self._closed:
            raise CacheBusy("ISR cache is shutting down")
        self._check_loop()
        keys = set(self._cached_paths) | set(self._variant_paths)
        if self.shared is not None:
            try:
                shared = await asyncio.to_thread(self.shared.keys)
            except Exception as exc:
                if self.failure_policy == FAIL_CLOSED:
                    raise SharedCacheUnavailable("Shared cache key listing failed") from exc
                log.warning("Shared cache key listing failed for scoped revalidation;"
                            " using process-local paths only", exc_info=True)
                shared = []
            for raw in shared:
                if not isinstance(raw, str):
                    continue
                key = raw[len(self.namespace):] if self.namespace and raw.startswith(self.namespace) else raw
                if key.startswith("\0isr:"):
                    continue
                keys.add(key)
        return sorted(keys)

    def _remember_variant_generation(self, path, token):
        self._variant_paths[path] = token
        self._variant_paths.move_to_end(path)
        while len(self._variant_paths) > _MAX_LOCAL_VARIANT_PATHS:
            self._variant_paths.popitem(last=False)

    async def variant_generation(self, path, *, invalidate=False):
        """Return a stable random generation, rotating it on invalidation.

        Old cache entries become unreachable even if a generation is still
        rendering, and are eventually evicted by the backend's normal TTL.
        """
        if self._closed:
            raise CacheBusy("ISR cache is shutting down")
        self._check_loop()
        had_local = path in self._variant_paths
        if self.shared is not None:
            try:
                token, existed = await asyncio.to_thread(
                    self.shared.variant_generation, self.namespace + path, invalidate=invalidate)
                self._report_backend(True)
                self._remember_variant_generation(path, token)
                return token, existed or had_local
            except Exception as exc:
                self._report_backend(False)
                self._report_degraded()
                if self.failure_policy == FAIL_CLOSED:
                    raise SharedCacheUnavailable("Shared cache generation failed") from exc
                log.warning("Shared cache generation failed for %s", path, exc_info=True)
        if invalidate or not had_local:
            token = uuid.uuid4().hex
        else:
            token = self._variant_paths[path]
        self._remember_variant_generation(path, token)
        return token, had_local

    def _register(self, key, task, owner=None):
        self._inflight[key] = task
        self._task_leases[task] = owner
        self._tasks.add(task)
        self.signal.begin_read()

        def completed(finished):
            self._tasks.discard(finished)
            self._task_leases.pop(finished, None)
            if self._inflight.get(key) is finished:
                self._inflight.pop(key, None)
            self.signal.end_read()
            if not finished.cancelled():
                error = finished.exception()
                if error is not None and not isinstance(error, (SignalError, ISRRenderStatusError)):
                    # A permanent 4xx render is a deterministic outcome,
                    # not a failure: like the dispatcher, do not log a
                    # signal as an error.
                    log.error("ISR regeneration failed for %s", key,
                              exc_info=(type(error), error, error.__traceback__))
        task.add_done_callback(completed)
        return task

    async def _wait_for_shared(self, key, timeout, signal=None):
        """Wait for another worker's first generation to land in the shared
        cache. Returns the fresh body, or None on timeout. If the other
        worker's lease expires while we wait, take the lease and report
        the observed version so the caller becomes the generator.

        ``signal`` (a :class:`CacheSignal`, normally this cache's own)
        lets the poll wake early: while local cache reads are in flight
        the wait ends as soon as they settle instead of sleeping out
        the poll interval, so a waiter re-checks the shared entry the
        moment a warmup or generation finishes. The poll interval stays
        ``LEASE_WAIT_INTERVAL`` as the worst-case cadence, and the loop
        re-checks the entry on every wake, so correctness never depends
        on the signal.
        """
        deadline = time.monotonic() + timeout
        owner = f"{os.getpid()}:{uuid.uuid4().hex}"
        while True:
            entry = await self._shared_entry(key)
            if entry is _SHARED_UNAVAILABLE:
                return ("unavailable", None)
            if entry is not None and entry.status == "fresh":
                return ("fresh", entry)
            if time.monotonic() >= deadline:
                return ("timeout", None)
            version = await self._shared_acquire(key, owner)
            if version is _SHARED_UNAVAILABLE:
                return ("unavailable", None)
            if version is not None:
                return ("lease", (version, owner))
            if signal is not None and signal.has_pending_reads():
                try:
                    await asyncio.wait_for(signal.cache_ready(), LEASE_WAIT_INTERVAL)
                except TimeoutError:
                    pass
            else:
                await asyncio.sleep(LEASE_WAIT_INTERVAL)

    def _remember_key_generated(self, key, generated_at=None):
        # ``generated_at`` is the render *start* time when the caller
        # knows it (see :meth:`_generate`): the local tag check compares
        # this against invalidation times, so a generation that started
        # before a ``revalidate_tag`` must not look fresh afterwards.
        self._key_generated_at[key] = time.time() if generated_at is None else generated_at
        self._key_generated_at.move_to_end(key)
        while len(self._key_generated_at) > _MAX_LOCAL_VARIANT_PATHS:
            self._key_generated_at.popitem(last=False)

    async def get_or_render(self, key, policy, render, *, tags=None):
        """Serve ``key`` from cache or render it once.

        ``tags`` are the cache tags the generated entry is stored with;
        when omitted they default to ``policy["tags"]`` (page tags
        passed through the policy dict). Tag invalidation judges the
        entry against these tags.
        """
        loop = asyncio.get_running_loop()
        if self._closed:
            raise CacheBusy("ISR cache is shutting down")
        if self._loop is None:
            self._loop = loop
        elif self._loop is not loop:
            raise RuntimeError("An ISR app instance must use a single event loop")
        if tags is None:
            # Tags may ride in the policy dict (page tags); an explicit
            # argument wins.
            tags = policy.get("tags", ())
        tags = _validate_entry_tags(tags)
        self._remember_key_tags(key, tags)
        # Normalize to the 3-axis policy, then hand the backends the two
        # windows they store: fresh_for = revalidate, stale_for =
        # expire - revalidate, so the SWR window runs up to the hard cap.
        # A pre-expire 2-key policy keeps its old meaning
        # (expire = revalidate + stale). A revalidate=False policy
        # normalizes to the longest lifetime (see normalize_isr_policy).
        fresh_for, stale_for = policy_windows(policy)
        policy = {"revalidate": fresh_for, "stale": stale_for}
        if not key.startswith("\0isr:"):
            # Plain cache keys are concrete paths; remember them so a
            # scoped revalidation can find this entry later. Hashed
            # query-variant keys are covered by _variant_paths instead.
            self._remember_cached_path(key)
        status, body = self.store.lookup(key)
        if status == "fresh":
            # A tag invalidation recorded locally reclassifies a
            # process-local hit before the shared store is consulted,
            # so the memory backend and shared-outage fallbacks honour
            # it too. The shared lookup below stays authoritative
            # whenever the shared store answers.
            tag_status = self._local_tag_status(key)
            if tag_status == "expired":
                self.store.remove(key)
                status, body = "miss", None
            elif tag_status == "stale":
                status = "stale"
        if status == "fresh" and self.shared is None:
            return body
        if self.shared is None:
            return await self._get_or_render_local(key, policy, render, status, body, tags)
        return await self._get_or_render_shared(key, policy, render, status, body, tags)

    async def warmup(self, entries, *, timeout=None):
        """Pre-fill the cache for ``entries`` without failing the caller.

        ``entries`` is an iterable of ``(key, policy, render)`` triples,
        the same shape :meth:`get_or_render` takes. Entries already
        fresh in the local cache are skipped (and duplicates after the
        first); the rest render concurrently through the normal
        single-flight path, so a warmup never duplicates a generation a
        request already started, and at most ``MAX_INFLIGHT``
        generations run at once.

        Completion is detected with :attr:`signal` — the warmup returns
        once the in-flight generation count reaches zero instead of
        polling. A per-entry failure is logged and counted, never
        raised: warmup is best-effort, and the entry is simply rendered
        on its first real request instead.

        Returns ``{"requested", "warmed", "skipped", "failed",
        "pending", "timed_out", "failures"}``; ``failures`` maps keys to
        ``"ErrorType: message"``. With ``timeout``, entries still
        running when the wait expires are reported as ``pending`` and
        keep generating in the background.
        """
        if self._closed:
            raise CacheBusy("ISR cache is shutting down")
        self._check_loop()
        outcomes = {}
        seen = set()
        requested = 0
        skipped = 0
        tasks = []
        semaphore = asyncio.Semaphore(MAX_INFLIGHT)
        for key, policy, render in entries:
            if key in seen:
                skipped += 1
                continue
            seen.add(key)
            requested += 1
            status, _ = self.store.lookup(key)
            if status == "fresh":
                skipped += 1
                continue
            tasks.append(asyncio.ensure_future(
                self._warm_one(key, policy, render, outcomes, semaphore)))
        timed_out = False
        try:
            async with asyncio.timeout(timeout):
                await self.signal.cache_ready()
                if tasks:
                    await asyncio.gather(*tasks)
        except TimeoutError:
            timed_out = True
            # gather() above already cancels the still-running warmups
            # when the timeout fires mid-gather; cancel any that were
            # still only queued behind cache_ready() and let each record
            # "pending" before it stops. The underlying generations are
            # shielded and keep running, so a timed-out entry still
            # lands in the cache.
            for task in tasks:
                if not task.done():
                    task.cancel()
            if tasks:
                await asyncio.gather(*tasks, return_exceptions=True)
        warmed = sum(1 for outcome in outcomes.values() if outcome == "warmed")
        pending = sum(1 for outcome in outcomes.values() if outcome == "pending")
        failures = {key: outcome[1] for key, outcome in outcomes.items()
                    if isinstance(outcome, tuple)}
        result = {"requested": requested, "warmed": warmed, "skipped": skipped,
                  "failed": len(failures), "pending": pending,
                  "timed_out": timed_out, "failures": failures}
        for key, error in failures.items():
            log.warning("ISR warmup failed for %s: %s", key, error)
        if timed_out:
            log.warning("ISR warmup timed out after %ss with %d entries still pending",
                        timeout, pending)
        return result

    async def _warm_one(self, key, policy, render, outcomes, semaphore):
        """Render one warmup entry and record its outcome."""
        try:
            async with semaphore:
                await self.get_or_render(key, policy, render)
        except asyncio.CancelledError:
            # The warmup wait expired (or the caller went away). The
            # generation itself is shielded and keeps running, so this
            # entry is pending, not failed.
            outcomes[key] = "pending"
            raise
        except Exception as exc:
            outcomes[key] = ("failed", f"{type(exc).__name__}: {exc}")
        else:
            outcomes[key] = "warmed"
    async def _generate(self, key, policy, render, lease=None, tags=(), previous_body=None):
        """Render once and store the result, fenced by the lease version.

        ``lease`` is ``(expected_version, owner)`` for a shared-cache
        generation that holds the cross-process lease. A fallback without a
        lease is stored only locally. A fenced-out generation still serves
        its own caller, but cannot replace either cache layer.

        When ``previous_body`` is given (a stale entry was being
        regenerated) and the render fails, the previous body is retained
        with tightened durations (Next.js ``retainPreviousCacheEntry``):
        it keeps serving while the next retry breathes 3..30s instead of
        the entry expiring on its original schedule and every request
        paying for a slow blocking render.
        """
        owner = lease[1] if lease is not None else None
        expected_version = lease[0] if lease is not None else None
        # Stamp the render start time now: the entry's ``generated_at``
        # must reflect when its content was produced, not when the
        # (possibly slow) render finished and stored it. Otherwise a
        # generation that started before a ``revalidate_tag`` but stored
        # after it looks "fresh" to the tag check even though its content
        # predates the invalidation. The same start time is recorded for
        # the process-local tag check (``_remember_key_generated``).
        started_at = time.time()
        started_mono = time.monotonic()
        try:
            async with asyncio.timeout(GENERATION_TIMEOUT):
                if lease is not None:
                    # Another worker may have populated the cache after our
                    # miss but before we obtained the now-free lease. Check
                    # again while holding the lease before rendering.
                    entry = await self._shared_entry(key)
                    if entry is not _SHARED_UNAVAILABLE and entry is not None and entry.status == "fresh":
                        if self._inflight.get(key) is asyncio.current_task():
                            self._store_insert(key, entry.body, entry.fresh_remaining, entry.stale_remaining)
                        self._clear_regen_failure(key)
                        return entry.body
                response = await render()
                if response.status != 200:
                    if 400 <= response.status < 500:
                        # C-2: a 4xx render is a permanent outcome for
                        # this key, not a failed regeneration. A deleted
                        # page (404) must reach the client instead of
                        # being masked by the retained previous body
                        # forever: no backoff is armed, the retained copy
                        # is dropped so no fallback path can resurrect
                        # it, and the outcome is re-raised as the
                        # matching signal (401/403/404) or as
                        # ISRRenderStatusError (other 4xx) so the
                        # callers below do not serve retention for it.
                        # A 5xx render keeps the old path: it may be
                        # transient, so it stays a regeneration failure
                        # with backoff + retained fallback.
                        self._drop_retained(key)
                        self._clear_regen_failure(key)
                        signal = _signal_for_status(response.status)
                        if signal is not None:
                            raise signal
                        raise ISRRenderStatusError(response.status, response.body)
                    raise ValueError("ISR can cache only successful page responses")
                # An invalidated generation may finish for existing callers,
                # but must never repopulate the cache after invalidation.
                if self._inflight.get(key) is asyncio.current_task():
                    if _is_storable(response):
                        shared_stored = True
                        coalesced = False
                        if self.shared is not None and owner is not None:
                            shared_stored, coalesced = await self._store_shared(
                                key, response.body, policy, expected_version, owner, tags,
                                generated_at=started_at, generated_mono=started_mono)
                            if not shared_stored:
                                log.warning("Shared ISR insert for %s failed or was fenced out;"
                                            " page was served but not cached", key)
                        # Do not populate L1 after a shared write was rejected,
                        # after this app invalidated the running task, or when a
                        # concurrent set already stored a fresh body (its body
                        # is in L1 already).
                        if shared_stored and not coalesced and self._inflight.get(key) is asyncio.current_task():
                            if self._store_insert(key, response.body, policy["revalidate"], policy["stale"]):
                                self._remember_key_generated(key, started_at)
                            else:
                                log.warning("ISR cache insert failed for %s; page was served but not cached", key)
                    else:
                        log.info("ISR response for %s is private; served but not cached", key)
                self._clear_regen_failure(key)
                return response.body
        except asyncio.CancelledError:
            raise
        except (SignalError, ISRRenderStatusError):
            # A permanent 4xx outcome is not a regeneration failure:
            # no backoff is recorded and the retained previous body is
            # never served for it (see the raise site above).
            raise
        except Exception as exc:
            # C-2: a failed regeneration never evicts the previous
            # entry; record it so the next retry backs off instead of
            # hammering the origin on every request.
            self._record_regen_failure(key, exc)
            if previous_body is not None and self._inflight.get(key) is asyncio.current_task():
                fresh, stale = _retain_durations(policy)
                shared_stored = True
                if self.shared is not None and owner is not None:
                    shared_stored = await self._shared_store(
                        key, previous_body, {"revalidate": fresh, "stale": stale},
                        expected_version, owner, tags)
                    if not shared_stored:
                        log.warning("Shared ISR retain for %s failed or was fenced out;"
                                    " previous entry was not extended", key)
                if shared_stored:
                    if not self._store_insert(key, previous_body, fresh, stale):
                        log.warning("ISR cache retain failed for %s; previous entry was not extended", key)
                log.warning("ISR regeneration failed for %s; retaining previous entry"
                            " (fresh %.0fs, stale %.0fs) before the next retry",
                            key, fresh, stale)
            raise
        finally:
            if owner is not None and self.shared is not None:
                await self._shared_release(key, owner)

    async def _get_or_render_local(self, key, policy, render, status, body, tags=()):
        # C-2 (retainPreviousCacheEntry): a stale entry is served while
        # one background regeneration runs — but while a failed
        # regeneration is backing off, serve it without starting
        # another one (SWR early-resolve; the retry gets its breathing
        # room instead of hammering the origin on every request).
        if status == "stale":
            if self._regen_backoff_remaining(key) <= 0:
                task = self._inflight.get(key)
                if task is None and len(self._tasks) < MAX_INFLIGHT:
                    task = self._register(key, asyncio.create_task(
                        self._generate(key, policy, render, tags=tags, previous_body=body),
                        context=contextvars.Context()))
            return body
        # Expired or miss: the backends have already dropped the entry,
        # so the retained previous value (if any) is the fallback. While
        # its retry backs off, serve it outright; otherwise regenerate
        # inline, and if that fails serve it instead of erroring.
        previous = body
        if previous is None:
            previous = await self._retained_body(key, tags)
        if previous is not None and self._regen_backoff_remaining(key) > 0:
            return previous
        task = self._inflight.get(key)
        if task is None and len(self._tasks) < MAX_INFLIGHT:
            task = self._register(key, asyncio.create_task(
                self._generate(key, policy, render, tags=tags), context=contextvars.Context()))
        if task is None:
            if previous is not None:
                return previous
            raise CacheBusy("Too many ISR generations")
        # A cancelled request must not cancel the shared render for other callers.
        try:
            return await asyncio.shield(task)
        except asyncio.CancelledError:
            raise
        except (SignalError, ISRRenderStatusError):
            # A permanent 4xx render must reach the caller, never the
            # retained previous body (C-2).
            raise
        except Exception:
            if previous is not None:
                return previous
            raise

    async def _get_or_render_shared(self, key, policy, render, status, body, tags=()):
        entry = await self._shared_entry(key)
        if entry is _SHARED_UNAVAILABLE:
            if status == "fresh":
                return body
            return await self._get_or_render_local(key, policy, render, status, body, tags)
        if entry is not None and entry.status == "fresh":
            # Keep a local fallback for shared-store outages. Shared mode
            # still validates each hit against the authoritative store.
            self._store_insert(key, entry.body, entry.fresh_remaining, entry.stale_remaining)
            return entry.body
        # A shared write for this key may be landing right now (Next.js
        # ``pendingSets``): wait for it to finish (bounded) and re-read, so
        # this request serves the new body instead of the previous version
        # or a duplicate render.
        refreshed = await self._await_pending_set(key)
        if refreshed is not None:
            entry = refreshed
            if entry.status == "fresh":
                self.store.insert(key, entry.body, entry.fresh_remaining, entry.stale_remaining)
                return entry.body
        task = self._inflight.get(key)
        if task is not None:
            owner = self._task_leases.get(task)
            try:
                valid = owner is not None and await asyncio.to_thread(
                    self.shared.owns_lease, self.namespace + key, owner)
            except Exception as exc:
                if self.failure_policy == FAIL_CLOSED:
                    raise SharedCacheUnavailable("Shared cache lease lookup failed") from exc
                if status == "fresh":
                    return body
                return await self._get_or_render_local(key, policy, render, status, body, tags)
            if not valid:
                if self._inflight.get(key) is task:
                    self._inflight.pop(key, None)
                task = None
        # C-2: while a failed regeneration backs off, a stale entry is
        # served without taking another lease or starting another
        # regeneration.
        if (entry is not None and entry.status == "stale"
                and self._regen_backoff_remaining(key) > 0):
            return entry.body
        if entry is None or entry.status == "expired":
            self.store.remove(key)
        if ((entry is None or entry.status == "expired")
                and self._regen_backoff_remaining(key) > 0):
            # Expired and backing off: serve the retained previous
            # value instead of regenerating (or erroring) right away.
            previous = await self._retained_body(key, tags)
            if previous is not None:
                return previous
        if task is None and len(self._tasks) < MAX_INFLIGHT:
            if entry is not None and entry.status == "stale":
                # Serve stale now; regenerate in the background, but only
                # the worker that wins the cross-process lease renders.
                owner = f"{os.getpid()}:{uuid.uuid4().hex}"
                version = await self._shared_acquire(key, owner)
                if version is _SHARED_UNAVAILABLE:
                    return await self._get_or_render_local(key, policy, render, "stale", entry.body, tags)
                if version is not None:
                    task = self._register(key, asyncio.create_task(
                        self._generate(key, policy, render, lease=(version, owner), tags=tags,
                                       previous_body=entry.body),
                        context=contextvars.Context()), owner)
                return entry.body
            # First generation (or expired): become the generator if the
            # lease is free, otherwise wait for the worker that holds it.
            owner = f"{os.getpid()}:{uuid.uuid4().hex}"
            version = await self._shared_acquire(key, owner)
            if version is _SHARED_UNAVAILABLE:
                return await self._get_or_render_local(key, policy, render, status, body, tags)
            if version is not None:
                task = self._register(key, asyncio.create_task(
                    self._generate(key, policy, render, lease=(version, owner), tags=tags),
                    context=contextvars.Context()), owner)
            else:
                outcome, payload = await self._wait_for_shared(key, GENERATION_TIMEOUT, self.signal)
                if outcome == "fresh":
                    entry = payload
                    self._store_insert(key, entry.body, entry.fresh_remaining, entry.stale_remaining)
                    return entry.body
                if outcome == "lease":
                    version, owner = payload
                    task = self._register(key, asyncio.create_task(
                        self._generate(key, policy, render, lease=(version, owner), tags=tags),
                        context=contextvars.Context()), owner)
                else:
                    # The other worker is still generating after the wait.
                    # Render locally rather than failing the request, but
                    # never write to the shared store without a lease.
                    if outcome == "timeout":
                        log.warning("ISR first generation for %s is still running in another worker;"
                                    " rendering locally", key)
                    task = self._register(key, asyncio.create_task(
                        self._generate(key, policy, render, tags=tags),
                        context=contextvars.Context()))
        if entry is not None and entry.status == "stale":
            return entry.body
        if task is None:
            # C-2: too busy to regenerate is still a regeneration
            # failure — serve the retained previous value instead of
            # erroring, when one exists (mirrors the local path).
            previous = await self._retained_body(key, tags)
            if previous is not None:
                return previous
            raise CacheBusy("Too many ISR generations")
        # A cancelled request must not cancel the shared render for other callers.
        try:
            return await asyncio.shield(task)
        except asyncio.CancelledError:
            raise
        except (SignalError, ISRRenderStatusError):
            # A permanent 4xx render must reach the caller, never the
            # retained previous body (C-2).
            raise
        except Exception:
            # C-2: a failed (re)generation serves the retained previous
            # value instead of erroring, when one exists.
            previous = await self._retained_body(key, tags)
            if previous is not None:
                return previous
            raise
