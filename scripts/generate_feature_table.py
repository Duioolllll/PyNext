#!/usr/bin/env python3
"""Generate docs/FEATURES.md from the code in this checkout.

The feature list is derived from the source tree with the standard
library only (``ast`` parsing, no package import), so it runs without
the Rust extension being built:

- package version / supported Python range: ``pyproject.toml``
- public API: ``python/pynext/__init__.py`` ``__all__`` + its imports
- security defaults: ``SecurityConfig`` fields in ``python/pynext/http.py``
- ISR cache backends: the backend tuple validated by ``ISRCache``
- CLI commands: ``add_parser`` calls in ``python/pynext/cli.py``
- server controls: ``add_argument`` calls in ``python/pynext/cli.py``
- health endpoints: request-path checks in ``python/pynext/app.py``
- island activation strategies: the strategy set in ``components.py``
- session stores: ``*Store`` classes in ``python/pynext/sessions.py``

Usage:
    python scripts/generate_feature_table.py            # write docs/FEATURES.md
    python scripts/generate_feature_table.py --check    # fail if docs/FEATURES.md is stale

``scripts/check_docs.py`` (and CI) run this script in ``--check`` mode so
a code change that adds, renames or removes a listed capability without
regenerating the table fails the docs job.
"""

from __future__ import annotations

import argparse
import ast
import difflib
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
GENERATED_HEADER = (
    "<!-- DO NOT EDIT BY HAND. Generated by scripts/generate_feature_table.py "
    "from the code in this checkout. Run `python scripts/generate_feature_table.py` "
    "to regenerate. -->\n"
)

# Short notes for backends whose names come from code. A backend that is
# removed from the code disappears from the table automatically.
BACKEND_NOTES = {
    "memory": "Process-local memory cache (default).",
    "sqlite": "Shared SQLite file; entries are visible to all workers.",
    "redis": "Shared Redis store via `PYNEXT_REDIS_URL`.",
}

# The build/dev/start subcommands carry no help= text in cli.py; these
# one-line notes are keyed by command name, so a command removed from
# the code still disappears from the table.
COMMAND_NOTES = {
    "build": "Build the application (SSG, islands, manifest).",
    "dev": "Start the development server with file watching.",
    "start": "Start the built application (production mode).",
}

# Non-goals are a deliberate policy statement, not something code can
# prove; the wording is kept in sync with docs/ROADMAP.md by
# scripts/check_docs.py, which asserts the same phrases appear there.
NON_GOALS = [
    ("React / React Server Components", "Explicit non-goal for 1.0 (see docs/ROADMAP.md)."),
    ("Django integration", "Deferred; ORM/forms only under consideration. ASGI sub-apps and templates are out of scope."),
]


def _parse(path: Path) -> ast.Module:
    return ast.parse(path.read_text(encoding="utf-8"), filename=str(path))


def _const(node: ast.AST):
    if isinstance(node, ast.Constant):
        return node.value
    return None


def _string_tuple(node: ast.AST) -> list[str] | None:
    if isinstance(node, (ast.Tuple, ast.List, ast.Set)):
        values = [_const(elt) for elt in node.elts]
        if all(isinstance(v, str) for v in values):
            return list(values)
    return None


def project_info() -> tuple[str, str, str]:
    data = tomllib.loads((ROOT / "pyproject.toml").read_text(encoding="utf-8"))
    project = data["project"]
    return project["name"], project["version"], project["requires-python"]


def public_api() -> list[tuple[str, str]]:
    """(symbol, source module) for every name in pynext.__all__."""
    tree = _parse(ROOT / "python" / "pynext" / "__init__.py")
    module_of: dict[str, str] = {}
    all_names: list[str] = []
    for node in ast.walk(tree):
        if isinstance(node, ast.ImportFrom) and node.module:
            for alias in node.names:
                module_of[alias.asname or alias.name] = node.module
        elif isinstance(node, ast.Assign):
            for target in node.targets:
                if isinstance(target, ast.Name) and target.id == "__all__":
                    names = _string_tuple(node.value)
                    if names is not None:
                        all_names = names
    return [(name, module_of.get(name, "?")) for name in all_names]


def security_defaults() -> list[tuple[str, str]]:
    """(field, default) for SecurityConfig in http.py."""
    tree = _parse(ROOT / "python" / "pynext" / "http.py")
    for node in ast.walk(tree):
        if isinstance(node, ast.ClassDef) and node.name == "SecurityConfig":
            rows = []
            for stmt in node.body:
                if isinstance(stmt, ast.AnnAssign) and isinstance(stmt.target, ast.Name):
                    default = ast.unparse(stmt.value) if stmt.value is not None else "-"
                    rows.append((stmt.target.id, default))
            return rows
    return []


def cache_backends() -> list[str]:
    tree = _parse(ROOT / "python" / "pynext" / "cache.py")
    for node in ast.walk(tree):
        if isinstance(node, ast.Compare):
            for comparator in node.comparators:
                values = _string_tuple(comparator)
                if values and "memory" in values:
                    return values
    return []


def cli_commands() -> list[tuple[str, str]]:
    """(command, help) for every add_parser call in cli.py."""
    tree = _parse(ROOT / "python" / "pynext" / "cli.py")
    commands: dict[str, str] = {}
    for node in ast.walk(tree):
        if isinstance(node, ast.Call):
            func = node.func
            if isinstance(func, ast.Attribute) and func.attr == "add_parser" and node.args:
                name = _const(node.args[0])
                help_text = ""
                for kw in node.keywords:
                    if kw.arg == "help":
                        help_text = _const(kw.value) or ""
                if isinstance(name, str):
                    commands[name] = help_text
        if isinstance(node, ast.For):
            values = _string_tuple(node.iter)
            if values and set(values) <= {"build", "dev", "start", "init"}:
                for name in values:
                    commands.setdefault(name, "")
    return sorted(commands.items())


def island_strategies() -> list[str]:
    tree = _parse(ROOT / "python" / "pynext" / "components.py")
    for node in ast.walk(tree):
        values = _string_tuple(node)
        if values and set(values) == {"load", "visible", "idle", "interaction"}:
            return sorted(values)
    return []


def session_stores() -> list[str]:
    tree = _parse(ROOT / "python" / "pynext" / "sessions.py")
    return sorted(
        node.name
        for node in ast.walk(tree)
        if isinstance(node, ast.ClassDef) and node.name.endswith("Store")
    )


def server_controls() -> list[tuple[str, str]]:
    """Extract selected operational CLI controls and their declared defaults."""
    wanted = {"--max-waiting", "--max-connections", "--max-connections-per-ip", "--shutdown-timeout"}
    rows = {}
    for node in ast.walk(_parse(ROOT / "python" / "pynext" / "cli.py")):
        if not (isinstance(node, ast.Call) and isinstance(node.func, ast.Attribute)
                and node.func.attr == "add_argument"):
            continue
        for arg in node.args:
            name = _const(arg)
            if name in wanted:
                default = next((ast.unparse(kw.value) for kw in node.keywords if kw.arg == "default"), "-")
                rows[name] = default
    return sorted(rows.items())


def health_endpoints() -> list[str]:
    """Extract the reserved liveness/readiness paths from dispatch."""
    for node in ast.walk(_parse(ROOT / "python" / "pynext" / "app.py")):
        if (isinstance(node, ast.Compare) and isinstance(node.left, ast.Attribute)
                and isinstance(node.left.value, ast.Name)
                and node.left.value.id == "request" and node.left.attr == "path"):
            for comparator in node.comparators:
                values = _string_tuple(comparator)
                if values and {"/healthz", "/readyz"}.issubset(values):
                    return sorted(values)
    return []


def render() -> str:
    name, version, requires_python = project_info()
    api = public_api()
    security = security_defaults()
    backends = cache_backends()
    commands = cli_commands()
    strategies = island_strategies()
    stores = session_stores()

    lines = [
        GENERATED_HEADER,
        "# PyNext capabilities",
        "",
        "Generated from the code in this checkout by "
        "`scripts/generate_feature_table.py`. Do not edit by hand; "
        "regenerate instead. If a capability below disagrees with the "
        "manuals, this file (the code) wins.",
        "",
        f"- Package: `{name}` **{version}** (see `pyproject.toml`)",
        f"- Supported Python: `{requires_python}`",
        f"- Canonical documentation: [English manual](en/manual.md)",
        "",
        "## Public API",
        "",
        "Exported from `pynext` (`python/pynext/__init__.py`).",
        "",
        "| Symbol | Module |",
        "| --- | --- |",
    ]
    for symbol, module in api:
        lines.append(f"| `{symbol}` | `pynext.{module}` |")
    lines += [
        "",
        "## Security defaults (`SecurityConfig`)",
        "",
        "Fields of `pynext.http.SecurityConfig` with their defaults.",
        "",
        "| Field | Default |",
        "| --- | --- |",
    ]
    for field, default in security:
        lines.append(f"| `{field}` | `{default}` |")
    lines += [
        "",
        "## ISR cache backends",
        "",
        "Backends accepted by `ISRCache` (`--cache-backend`, `create_app(..., cache_backend=...)`).",
        "",
        "| Backend | Notes |",
        "| --- | --- |",
    ]
    for backend in backends:
        lines.append(f"| `{backend}` | {BACKEND_NOTES.get(backend, '')} |")
    lines += [
        "",
        "## CLI commands (`pynext`)",
        "",
        "| Command | Help |",
        "| --- | --- |",
    ]
    for command, help_text in commands:
        lines.append(f"| `{command}` | {help_text or COMMAND_NOTES.get(command, '')} |")
    lines += [
        "",
        "## Server controls (`pynext dev` / `pynext start`)",
        "",
        "CLI defaults of `None` defer to server defaults; see the manual for scope and units.",
        "",
        "| Option | CLI default |",
        "| --- | --- |",
    ]
    for option, default in server_controls():
        lines.append(f"| `{option}` | `{default}` |")
    lines += [
        "",
        "## Health endpoints",
        "",
        "Reserved GET/HEAD paths; readiness reflects startup and draining, not upstream health.",
        "",
        "| Path |",
        "| --- |",
    ]
    for endpoint in health_endpoints():
        lines.append(f"| `{endpoint}` |")
    lines += [
        "",
        "## Island activation strategies",
        "",
        "Strategies accepted by `island()` / `page()` in `pynext.components`.",
        "",
        "| Strategy |",
        "| --- |",
    ]
    for strategy in strategies:
        lines.append(f"| `{strategy}` |")
    lines += [
        "",
        "## Session stores",
        "",
        "Store classes in `pynext.sessions` implementing `load` / `save` / `delete`.",
        "",
        "| Store |",
        "| --- |",
    ]
    for store in stores:
        lines.append(f"| `{store}` |")
    lines += [
        "",
        "## Explicit non-goals",
        "",
        "| Item | Status |",
        "| --- | --- |",
    ]
    for item, status in NON_GOALS:
        lines.append(f"| {item} | {status} |")
    lines.append("")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true",
                        help="fail if docs/FEATURES.md differs from the generated output")
    args = parser.parse_args(argv)
    output = render()
    target = ROOT / "docs" / "FEATURES.md"
    if args.check:
        current = target.read_text(encoding="utf-8") if target.exists() else ""
        if current != output:
            diff = "".join(difflib.unified_diff(
                current.splitlines(keepends=True), output.splitlines(keepends=True),
                fromfile="docs/FEATURES.md (on disk)", tofile="docs/FEATURES.md (generated)"))
            print("docs/FEATURES.md is stale. Run `python scripts/generate_feature_table.py` to regenerate:\n" + diff)
            return 1
        print("docs/FEATURES.md is up to date.")
        return 0
    target.write_text(output, encoding="utf-8")
    print(f"Wrote {target}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
